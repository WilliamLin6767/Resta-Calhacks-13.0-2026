-- =====================================================================
-- Email inbox: supplier invoices and customer orders that arrive by email.
-- A supplier's invoice is read like a scanned one; a customer's order waits
-- for the owner to confirm before it counts as a sale.
-- Run AFTER 09_sales_receipts.sql. Safe to re-run. Adds one table, and gives
-- the demo suppliers example email addresses where they have none.
-- =====================================================================

create table if not exists inbound_emails (
  id              bigint generated by default as identity primary key,
  restaurant_id   bigint not null references restaurants(id) on delete cascade,
  message_id      text not null,                 -- the email's Message-ID, so a resend isn't read twice
  from_email      text not null,
  from_name       text,
  subject         text,
  body            text,                          -- plain text, trimmed
  attachments     jsonb not null default '[]',   -- [{ name, type, size }]
  -- An unknown sender's invoice attachment waits here until the owner says to read it
  held_file       text,                          -- base64
  held_file_type  text,
  kind            text not null default 'unknown'
                  check (kind in ('supplier_invoice', 'customer_order', 'other', 'unknown')),
  status          text not null default 'new'
                  check (status in ('new', 'done', 'needs_review', 'to_confirm', 'confirmed', 'declined', 'ignored', 'error')),
  supplier_id     bigint references suppliers(id) on delete set null,
  invoice_id      bigint references invoices(id) on delete set null,
  customer_order  jsonb,                         -- { customer_name, pickup_date, pickup_time, lines: [{ menu_item_id, name, qty, unit_price }], notes }
  order_id        bigint references orders(id) on delete set null,
  note            text,                          -- what happened, in plain words
  created_at      timestamptz not null default now(),
  unique (restaurant_id, message_id)
);
create index if not exists inbound_emails_recent on inbound_emails (restaurant_id, created_at desc);

