-- DEMO ONLY: anyone with the publishable key can read and write. Same as the other tables.
-- Supabase no longer grants new tables to these roles automatically, so grant explicitly.
grant select, insert, update, delete on inbound_emails to anon, authenticated, service_role;
grant usage, select on sequence inbound_emails_id_seq to anon, authenticated, service_role;
do $$
begin
  alter table inbound_emails enable row level security;
  if not exists (select 1 from pg_policies where tablename = 'inbound_emails' and policyname = 'demo full access') then
    create policy "demo full access" on inbound_emails for all to anon, authenticated using (true) with check (true);
  end if;
end $$;
