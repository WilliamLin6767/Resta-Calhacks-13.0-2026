-- =====================================================================
-- Calls: phone calls to suppliers, placed by an AI agent (Wajo's Fo)
-- only after the owner approves each one.
-- Run AFTER 01_schema.sql, 02_seed.sql and 04_purchasing.sql. Safe to re-run
-- ("create table if not exists"; the policy is only added once).
-- (Same table as 10_calls.sql in the older copy of the app: if you ran that one
-- on this Supabase project, call_requests already exists and this does nothing.)
--
-- Only ADDS a table. Nothing existing is changed or dropped.
-- See lib/calls/README.md for how requests flow.
-- =====================================================================

create table if not exists call_requests (
  id             bigint generated by default as identity primary key,
  restaurant_id  bigint not null references restaurants(id) on delete cascade,
  supplier_id    bigint not null references suppliers(id) on delete cascade,

  -- The record the request shows up on.
  context_type   text not null check (context_type in ('invoice', 'supplier', 'ingredient', 'purchase_order')),
  context_id     bigint not null,

  purpose        text not null check (purpose in ('buy', 'dispute', 'info', 'special_request')),
  title          text not null,           -- e.g. 'Dispute $42 overcharge on invoice 10293'
  reason         text not null,           -- why a call is needed, shown to the owner
  brief          jsonb not null,          -- what the caller is told (lib/calls/brief.ts)

  status         text not null default 'pending'
                   check (status in ('pending', 'approved', 'rejected', 'calling', 'needs_input', 'completed', 'failed')),
  proposed_by    text not null check (proposed_by in ('ai', 'owner')),

  wajo_call_id   text,                    -- Wajo's conversationId for this call
  dialed_number  text,                    -- the number actually dialed (E.164)
  progress       text,                    -- Wajo's latest one-line status while calling
  question       text,                    -- when status = needs_input: what the caller is asking the owner
  last_polled_at timestamptz,             -- so status checks hit Wajo at most every 5 seconds

  outcome        text,                    -- plain-language summary, two sentences
  result         jsonb,                   -- structured result (lib/calls/types.ts StoredResult)
  transcript     text,

  created_at     timestamptz not null default now(),
  decided_at     timestamptz,
  completed_at   timestamptz,
  error          text
);

create index if not exists call_requests_context on call_requests (context_type, context_id, status);
create index if not exists call_requests_supplier on call_requests (supplier_id, status);

-- DEMO ONLY: anyone with the publishable key can read and write. Same as the other tables.
do $$
begin
  alter table call_requests enable row level security;
  if not exists (select 1 from pg_policies where tablename = 'call_requests' and policyname = 'demo full access') then
    create policy "demo full access" on call_requests for all to anon, authenticated using (true) with check (true);
  end if;
end $$;
