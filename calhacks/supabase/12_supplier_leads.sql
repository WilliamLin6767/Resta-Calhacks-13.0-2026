-- =====================================================================
-- ThomasNet call leads. Run AFTER 01_schema.sql. Safe to re-run.
--
-- Adds one table. Does not write suppliers or supplier_prices, so food
-- cost and the existing purchase-order flow stay unchanged.
-- =====================================================================

create table if not exists supplier_leads (
  id               bigint generated by default as identity primary key,
  source           text not null default 'thomasnet',
  ingredient_name  text not null,
  company_name     text not null,
  phone            text not null,
  website          text,
  city             text,
  state            text,
  matched_product  text,
  tgrams_id        text,
  scraped_at       timestamptz not null default now()
);

create index if not exists supplier_leads_ingredient on supplier_leads (ingredient_name);

-- DEMO ONLY: anyone with the publishable key can read and write. Same as the other tables.
do $$
begin
  alter table supplier_leads enable row level security;
  if not exists (select 1 from pg_policies where tablename = 'supplier_leads' and policyname = 'demo full access') then
    create policy "demo full access" on supplier_leads for all to anon, authenticated using (true) with check (true);
  end if;
end $$;
