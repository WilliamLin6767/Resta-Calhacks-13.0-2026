-- =====================================================================
-- Menu pricing (A4): delivery-app prices and a log of every price change.
-- Run AFTER 01_schema.sql and 02_seed.sql.
--
-- This file only ADDS a column and a table. It does not change or drop anything
-- from 01-04, so it's safe to run on top of the existing data, and safe to re-run.
-- =====================================================================

-- Delivery apps keep a commission, so restaurants usually charge more there.
-- null = the app shows the same price as the in-house menu.
alter table menu_items
  add column if not exists delivery_price numeric(10,2);

-- Every price change the owner approves. The app can't change prices in the POS or
-- on DoorDash / Uber Eats by itself yet, so each change has a checkbox per system:
-- the owner ticks it after updating that system, and the page shows what's still out of date.
create table if not exists menu_price_changes (
  id                  bigint generated by default as identity primary key,
  restaurant_id       bigint not null references restaurants(id) on delete cascade,
  menu_item_id        bigint not null references menu_items(id) on delete cascade,
  old_price           numeric(10,2) not null,
  new_price           numeric(10,2) not null,
  old_delivery_price  numeric(10,2),  -- null = same as the in-house price
  new_delivery_price  numeric(10,2),
  reason              text,
  changed_at          timestamptz not null default now(),
  pos_updated         boolean not null default false,
  doordash_updated    boolean not null default false,
  ubereats_updated    boolean not null default false
);
create index if not exists menu_price_changes_item on menu_price_changes (menu_item_id, changed_at desc);

-- DEMO ONLY: anyone with the publishable key can read and write. Same as the other tables.
do $$
begin
  alter table menu_price_changes enable row level security;
  if not exists (select 1 from pg_policies where tablename = 'menu_price_changes' and policyname = 'demo full access') then
    create policy "demo full access" on menu_price_changes for all to anon, authenticated using (true) with check (true);
  end if;
end $$;
