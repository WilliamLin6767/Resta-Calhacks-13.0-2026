-- =====================================================================
-- Invoice disputes: billing errors found on an invoice (04_purchasing.sql)
-- become a dispute email Claude drafts and the owner sends from their own
-- email, tracked until the supplier sends a credit or says no.
-- Run AFTER 04_purchasing.sql. Safe to re-run. Adds one table only.
-- =====================================================================

create table if not exists invoice_disputes (
  id              bigint generated by default as identity primary key,
  restaurant_id   bigint not null references restaurants(id) on delete cascade,
  invoice_id      bigint not null references invoices(id) on delete cascade,
  supplier_id     bigint references suppliers(id) on delete set null,
  status          text not null default 'draft' check (status in ('draft', 'sent', 'credited', 'refused')),
  amount_claimed  numeric(10,2) not null,  -- the billing errors on the invoice, at the time
  amount_credited numeric(10,2),           -- what the supplier gave back
  flag_ids        bigint[] not null default '{}', -- the invoice_flags this dispute covers
  to_email        text,
  subject         text,
  body            text,
  created_at      timestamptz not null default now(),
  sent_at         timestamptz,
  closed_at       timestamptz
);
create index if not exists invoice_disputes_invoice on invoice_disputes (invoice_id, created_at desc);

-- DEMO ONLY: anyone with the publishable key can read and write. Same as the other tables.
do $$
begin
  alter table invoice_disputes enable row level security;
  if not exists (select 1 from pg_policies where tablename = 'invoice_disputes' and policyname = 'demo full access') then
    create policy "demo full access" on invoice_disputes for all to anon, authenticated using (true) with check (true);
  end if;
end $$;
