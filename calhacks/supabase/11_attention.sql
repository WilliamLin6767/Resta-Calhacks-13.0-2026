-- =====================================================================
-- "Needs you" bar at the top of each tab: what the owner dismissed, and the
-- AI summary saved per tab. Run AFTER 01_schema.sql. Safe to re-run.
-- Adds two tables only.
-- =====================================================================

-- An alert the owner dismissed. `fingerprint` describes the alert when it was
-- dismissed (e.g. which items were low); if the alert changes, the fingerprint
-- no longer matches and it shows again.
create table if not exists attention_dismissals (
  id            bigint generated by default as identity primary key,
  restaurant_id bigint not null references restaurants(id) on delete cascade,
  item_key      text not null,
  fingerprint   text not null,
  dismissed_at  timestamptz not null default now(),
  unique (restaurant_id, item_key, fingerprint)
);

-- The AI summary for one tab, reused until the tab's numbers change (facts_hash).
create table if not exists ai_tab_summaries (
  id            bigint generated by default as identity primary key,
  restaurant_id bigint not null references restaurants(id) on delete cascade,
  tab           text not null,
  facts_hash    text not null,
  summary       jsonb not null,
  model         text,
  created_at    timestamptz not null default now()
);
create index if not exists ai_tab_summaries_lookup on ai_tab_summaries (restaurant_id, tab, facts_hash);

-- DEMO ONLY: anyone with the publishable key can read and write. Same as the other tables.
do $$
declare t text;
begin
  foreach t in array array['attention_dismissals', 'ai_tab_summaries'] loop
    execute format('alter table %I enable row level security', t);
    if not exists (select 1 from pg_policies where tablename = t and policyname = 'demo full access') then
      execute format('create policy "demo full access" on %I for all to anon, authenticated using (true) with check (true)', t);
    end if;
  end loop;
end $$;
