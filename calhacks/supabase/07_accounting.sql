  if not exists (select 1 from pg_policies where tablename = 'platform_payouts' and policyname = 'demo full access') then
    create policy "demo full access" on platform_payouts for all to anon, authenticated using (true) with check (true);
  end if;
end $$;

-- ---------------------------------------------------------------------
-- INVENTED SAMPLE DATA. One payout per platform per week (Monday-Sunday),
-- paid the Wednesday after, matching the sample orders, with two planted problems:
--   * DoorDash took an $86.40 "error charge" out of one week.
--   * Uber Eats never paid one week.
-- Only runs if there are no payouts yet.
-- ---------------------------------------------------------------------
do $$
begin
  if exists (select 1 from platform_payouts where restaurant_id = 1) then return; end if;

  insert into platform_payouts (restaurant_id, platform, period_start, period_end, paid_on, gross_sales, fees, net_amount, reference)
  select 1, channel, wk, wk + 6, wk + 9, sum(revenue), sum(platform_fees), sum(revenue) - sum(platform_fees),
         upper(left(channel, 2)) || '-' || to_char(wk, 'YYYYMMDD')
  from (select date_trunc('week', day)::date as wk, channel, revenue, platform_fees
        from v_daily_sales where restaurant_id = 1 and channel in ('doordash', 'ubereats')) d
  where wk + 9 < current_date      -- only weeks that are over and paid by now
  group by wk, channel;

  -- Planted problem 1: an error charge on a DoorDash week three weeks back
  update platform_payouts
     set adjustments = -86.40, net_amount = net_amount - 86.40, note = 'Error charge: order marked missing items'
   where restaurant_id = 1 and platform = 'doordash'
     and period_start = (select period_start from platform_payouts where restaurant_id = 1 and platform = 'doordash' order by period_start desc offset 2 limit 1);

  -- Planted problem 2: a Uber Eats week that was never paid
  delete from platform_payouts
   where restaurant_id = 1 and platform = 'ubereats'
     and period_start = (select period_start from platform_payouts where restaurant_id = 1 and platform = 'ubereats' order by period_start desc offset 3 limit 1);

  -- Sample bills already marked paid: assume they were paid on the due date
  update invoices set paid_at = due_date where restaurant_id = 1 and status = 'paid' and paid_at is null;
end $$;
