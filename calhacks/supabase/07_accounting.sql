-- What DoorDash / Uber Eats actually paid out for a period.
-- (Their merchant APIs need partner approval, so in real use these come
-- from the payout statements, typed in or read from a PDF/CSV.)
create table if not exists platform_payouts (
  id            bigint generated by default as identity primary key,
  restaurant_id bigint not null references restaurants(id) on delete cascade,
  platform      text not null check (platform in ('doordash', 'ubereats')),
  period_start  date not null,
  period_end    date not null,
  paid_on       date not null,
  gross_sales   numeric(10,2) not null,   -- order subtotals the platform reports
  fees          numeric(10,2) not null,   -- commission
  adjustments   numeric(10,2) not null default 0, -- error charges, refunds (negative) or credits (positive)
  net_amount    numeric(10,2) not null,   -- what landed in the bank
  reference     text,
  note          text,                     -- the platform's explanation of adjustments
  created_at    timestamptz not null default now(),
  unique (restaurant_id, platform, period_start)
);

-- When a bill was paid, for the bills list and the QuickBooks export.
alter table invoices add column if not exists paid_at date;

-- DEMO ONLY: anyone with the publishable key can read and write. Same as the other tables.
do $$
begin
