-- =====================================================================
-- Sales receipts: a scanned customer receipt becomes an order, and the
-- ingredients its dishes use come off inventory right away.
-- Run AFTER 06_prep.sql and 08_inventory.sql. Safe to re-run.
--
-- Adds one table and one read-only function. Changes nothing else.
-- =====================================================================

-- Each scanned receipt, linked to the order it created. Used to stop the
-- same receipt being added twice.
create table if not exists sales_receipts (
  id             bigint generated by default as identity primary key,
  restaurant_id  bigint not null references restaurants(id) on delete cascade,
  order_id       bigint references orders(id) on delete cascade,
  receipt_number text,
  receipt_date   date not null,
  total          numeric(10,2),
  source         text not null default 'photo' check (source in ('photo', 'manual')),
  created_at     timestamptz not null default now()
);
create index if not exists sales_receipts_lookup on sales_receipts (restaurant_id, receipt_date, receipt_number);

-- Dishes sold today so far. dish_sales_by_day (06) only covers finished
-- days, for forecasting; inventory also needs today's sales.
create or replace function dish_sales_today(p_restaurant_id bigint)
returns table (menu_item_id bigint, units bigint)
language sql
stable
security invoker
as $$
  select oi.menu_item_id, sum(oi.qty)::bigint
  from orders o
  join order_items oi on oi.order_id = o.id
  where o.restaurant_id = p_restaurant_id
    and (o.ordered_at at time zone 'America/Los_Angeles')::date = (now() at time zone 'America/Los_Angeles')::date
  group by 1
$$;

-- DEMO ONLY: anyone with the publishable key can read and write. Same as the other tables.
do $$
begin
  alter table sales_receipts enable row level security;
  if not exists (select 1 from pg_policies where tablename = 'sales_receipts' and policyname = 'demo full access') then
    create policy "demo full access" on sales_receipts for all to anon, authenticated using (true) with check (true);
  end if;
end $$;
