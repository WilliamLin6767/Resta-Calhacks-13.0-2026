-- =====================================================================
-- Cash plan (Capital One Nessie): a SIMULATED savings account next to the
-- operating account from 13_bank.sql, and the transfers the owner approved.
-- Run AFTER 13_bank.sql. Safe to re-run. Adds one column and one table.
-- =====================================================================

-- The simulated savings account, made the first time the owner moves money to it
alter table bank_links add column if not exists nessie_savings_id text;

-- Each move to savings the owner approved. Nessie records the transfer but doesn't change
-- either account's balance, so balances are worked out from these rows.
create table if not exists bank_transfers (
  id                 bigint generated by default as identity primary key,
  restaurant_id      bigint not null references restaurants(id) on delete cascade,
  nessie_transfer_id text not null unique,
  nessie_deposit_id  text not null unique, -- the matching deposit on the savings account
  amount             numeric(10,2) not null check (amount > 0),
  created_at         timestamptz not null default now()
);

-- DEMO ONLY: anyone with the publishable key can read and write. Same as the other tables.
do $$
begin
  alter table bank_transfers enable row level security;
  if not exists (select 1 from pg_policies where tablename = 'bank_transfers' and policyname = 'demo full access') then
    create policy "demo full access" on bank_transfers for all to anon, authenticated using (true) with check (true);
  end if;
end $$;
