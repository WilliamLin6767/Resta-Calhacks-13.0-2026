-- =====================================================================
-- The autonomous loop's cases (lib/loop/engine.ts). Run AFTER 18. Safe to re-run.
--
-- One case per problem the loop found: detected -> investigating -> proposed -> (owner approves
-- on a card) -> measuring -> closed, or dismissed / failed. Each step claims the case with a
-- conditional update, so overlapping ticks are safe. The partial unique index keeps one open case
-- per finding.
--
-- Adds one table. Changes nothing else.
-- =====================================================================

create table if not exists cases (
  id            bigint generated by default as identity primary key,
  restaurant_id bigint not null references public.restaurants(id) on delete cascade,
  playbook      text not null,                 -- supplier_price_rise, sales_dip, stockout_risk
  finding_key   text not null,                 -- e.g. price-rise:4, sales-dip:lunch:weekday
  status        text not null default 'detected',
  facts         jsonb not null default '{}',   -- what detect found, worked out in code
  evidence      jsonb not null default '[]',
  proposal      jsonb,                         -- the agent's recommendation and the action ids
  goal          jsonb,                         -- { metric, direction, target }
  baseline      jsonb,                         -- { method, value }
  window_start  timestamptz,
  window_end    timestamptz,
  result        jsonb,                         -- { value, baseline, difference, sample, cost, verdict }
  report        text,
  lesson        jsonb,                         -- { playbook, action, item, verdict, difference }
  error         text,
  is_demo       boolean not null default false,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  closed_at     timestamptz,
  constraint cases_status check (status in ('detected', 'investigating', 'proposed', 'approved', 'running', 'measuring', 'closed', 'dismissed', 'failed'))
);

-- One open case per finding
create unique index if not exists cases_one_open_per_finding
  on cases (restaurant_id, finding_key)
  where status not in ('closed', 'dismissed', 'failed');

create index if not exists cases_restaurant_status on cases (restaurant_id, status);
create index if not exists cases_playbook_closed on cases (restaurant_id, playbook, closed_at desc);

-- Server only, like every table after 17_lockdown.sql
do $$
begin
  alter table cases enable row level security;
  if not exists (select 1 from pg_policies where tablename = 'cases' and policyname = 'server only') then
    create policy "server only" on cases for all to service_role using (true) with check (true);
  end if;
end $$;
revoke all on cases from anon, authenticated;
grant all on cases to service_role;
