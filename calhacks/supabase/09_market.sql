-- =====================================================================
-- USDA AMS market quotes (public livestock and dairy prices).
-- Run AFTER 01_schema.sql. Safe to re-run.
--
-- Adds one table. Nothing is dropped, and nothing is written into
-- supplier_prices. These rows are a market index, not a vendor.
-- =====================================================================

create table if not exists market_quotes (
  id                 bigint generated by default as identity primary key,
  source             text not null default 'usda_ams',
  report_id          bigint,
  commodity          text,
  class              text,
  category           text,
  market_location    text,
  report_date        date,
  price_avg          numeric,
  price_low          numeric,
  price_high         numeric,
  price_unit         text,
  ingredient_family  text check (ingredient_family in ('beef', 'dairy')),
  cache_refreshed_at timestamptz,
  created_at         timestamptz not null default now()
);

create index if not exists market_quotes_family_date
  on market_quotes (ingredient_family, report_date);

-- DEMO ONLY: anyone with the publishable key can read and write. Same as the other tables.
do $$
begin
  alter table market_quotes enable row level security;
  if not exists (select 1 from pg_policies where tablename = 'market_quotes' and policyname = 'demo full access') then
    create policy "demo full access" on market_quotes for all to anon, authenticated using (true) with check (true);
  end if;
end $$;
