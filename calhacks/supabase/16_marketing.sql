-- =====================================================================
-- Marketing posts the owner drafts and sends to Instagram. Run AFTER 01_schema.sql.
-- Safe to re-run.
--
-- Adds one table and a public storage bucket. Does not write menu_items.
-- The bucket is public so Buffer can fetch the JPEG. Writes stay on the server.
-- =====================================================================

create table if not exists marketing_posts (
  id              bigint generated by default as identity primary key,
  restaurant_id   bigint not null references restaurants(id) on delete cascade,
  layout          text not null,
  dish_name       text not null,
  headline        text not null,
  subhead         text not null,
  caption         text not null,
  hashtags        text[] not null default '{}',
  image_path      text,
  status          text not null default 'draft',
  buffer_post_id  text,
  external_link   text,
  error           text,
  created_at      timestamptz not null default now(),
  posted_at       timestamptz,
  constraint marketing_posts_status check (status in ('draft', 'posted', 'failed'))
);

create index if not exists marketing_posts_restaurant
  on marketing_posts (restaurant_id, created_at desc);

insert into storage.buckets (id, name, public)
values ('marketing', 'marketing', true)
on conflict (id) do update set public = true;

-- DEMO ONLY: anyone with the publishable key can read and write. Same as the other tables.
do $$
begin
  alter table marketing_posts enable row level security;
  if not exists (select 1 from pg_policies where tablename = 'marketing_posts' and policyname = 'demo full access') then
    create policy "demo full access" on marketing_posts for all to anon, authenticated using (true) with check (true);
  end if;
  if not exists (
    select 1 from pg_policies
    where schemaname = 'storage' and tablename = 'objects' and policyname = 'marketing demo access'
  ) then
    create policy "marketing demo access" on storage.objects
      for all to anon, authenticated
      using (bucket_id = 'marketing')
      with check (bucket_id = 'marketing');
  end if;
end $$;
