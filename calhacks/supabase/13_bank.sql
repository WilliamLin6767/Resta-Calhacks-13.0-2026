-- =====================================================================
-- Bank check (Capital One Nessie): a SIMULATED bank account for the demo
-- restaurant, so delivery payouts can be checked against what reached the
-- bank, and restock orders against the cash left after upcoming bills.
-- Run AFTER 07_accounting.sql. Safe to re-run. Adds two tables only.
-- =====================================================================

-- The restaurant's simulated Nessie customer and checking account, and the
-- cash the owner wants to keep in the bank at all times.
create table if not exists bank_links (
  restaurant_id      bigint primary key references restaurants(id) on delete cascade,
  nessie_customer_id text not null,
  nessie_account_id  text not null,
  cash_reserve       numeric(10,2) not null default 1000,
  created_at         timestamptz not null default now()
);

-- Which Nessie deposit stands for which delivery payout. Nessie keeps whole
-- dollars only, so the exact amount (with cents) is kept here.
create table if not exists bank_deposit_links (
  id                bigint generated by default as identity primary key,
  restaurant_id     bigint not null references restaurants(id) on delete cascade,
  payout_id         bigint not null references platform_payouts(id) on delete cascade,
  nessie_deposit_id text not null unique,
  amount            numeric(10,2) not null,
  created_at        timestamptz not null default now(),
  unique (payout_id)
);

-- DEMO ONLY: anyone with the publishable key can read and write. Same as the other tables.
do $$
declare t text;
begin
  foreach t in array array['bank_links', 'bank_deposit_links'] loop
    execute format('alter table %I enable row level security', t);
    if not exists (select 1 from pg_policies where tablename = t and policyname = 'demo full access') then
      execute format('create policy "demo full access" on %I for all to anon, authenticated using (true) with check (true)', t);
    end if;
  end loop;
end $$;
