-- =====================================================================
-- Inventory (A2): deliveries into stock, counts from photos or voice, waste.
-- Run AFTER 01_schema.sql, 02_seed.sql and 04_purchasing.sql. Safe to re-run.
--
-- Adds a table and a column, and lets inventory_counts.source also be
-- 'voice' (the only change to an existing rule). Nothing is dropped.
-- =====================================================================

-- Every change to stock and why: a delivery, a count (with how far it was off), or waste.
create table if not exists stock_events (
  id              bigint generated by default as identity primary key,
  restaurant_id   bigint not null references restaurants(id) on delete cascade,
  ingredient_id   bigint not null references ingredients(id) on delete cascade,
  kind            text not null check (kind in ('delivery', 'count', 'waste')),
  change          numeric(10,2) not null,  -- + added, - removed; for a count, counted minus expected
  qty_after       numeric(10,2) not null,
  reason          text,                    -- waste: spoiled, dropped, expired... ; delivery: invoice number
  unit_cost       numeric(10,4),           -- cost per unit at the time, to value waste and count gaps
  invoice_line_id bigint references invoice_lines(id) on delete set null,
  source          text,                    -- photo, voice, manual, invoice
  created_at      timestamptz not null default now()
);
create index if not exists stock_events_recent on stock_events (restaurant_id, created_at desc);

-- So each invoice line is added to stock once, even if it's matched later.
alter table invoice_lines add column if not exists added_to_stock boolean not null default false;
-- The sample invoices (ids 1-8 in 02_seed.sql) are already part of the sample stock levels.
update invoice_lines set added_to_stock = true where invoice_id <= 8 and added_to_stock = false;

-- Counts can come from a voice note too
alter table inventory_counts drop constraint if exists inventory_counts_source_check;
alter table inventory_counts add constraint inventory_counts_source_check check (source in ('manual', 'invoice', 'estimate', 'photo', 'voice'));

-- DEMO ONLY: anyone with the publishable key can read and write. Same as the other tables.
do $$
begin
  alter table stock_events enable row level security;
  if not exists (select 1 from pg_policies where tablename = 'stock_events' and policyname = 'demo full access') then
    create policy "demo full access" on stock_events for all to anon, authenticated using (true) with check (true);
  end if;
end $$;
