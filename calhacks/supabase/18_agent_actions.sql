-- =====================================================================
-- One action log and approval gate (lib/agent/actions.ts). Run AFTER 17. Safe to re-run.
--
-- Every Commit action (anything that spends money, changes a price, contacts someone outside
-- the restaurant or moves money) is a row here. The agent and the loop can only insert
-- 'proposed' rows; only the owner's approve route moves one on, and execution claims the row
-- with a conditional update so it runs exactly once. The owner's own buttons write here too,
-- so the log is complete whichever way the owner acts.
--
-- Adds one table. Changes nothing else.
-- =====================================================================

create table if not exists agent_actions (
  id            bigint generated by default as identity primary key,
  restaurant_id bigint not null references public.restaurants(id) on delete cascade,
  case_id       bigint,                         -- the loop's case (19_cases.sql), when it came from one
  tool          text not null,                  -- e.g. place_call, set_menu_price
  tier          text not null default 'commit',
  title         text not null,                  -- short: "Call Valley Butcher about brisket"
  summary       text not null,                  -- exactly what will happen
  args          jsonb not null default '{}',    -- resolved ids and values, never free text from the model
  evidence      jsonb not null default '[]',
  impact        jsonb,                          -- { amount_usd, per: "week" | "once", basis, assumptions }
  status        text not null default 'proposed',
  source        text not null default 'agent',  -- agent, loop, owner
  surface       text,                           -- chat, voice, panel, loop, page
  approved_at   timestamptz,
  approved_by   text,                           -- the owner's session
  result        jsonb,                          -- links the record it made or changed (call id, PO id, post id)
  error         text,
  created_at    timestamptz not null default now(),
  done_at       timestamptz,
  expires_at    timestamptz not null default (now() + interval '48 hours'),
  constraint agent_actions_status check (status in ('proposed', 'approved', 'running', 'done', 'failed', 'rejected', 'undone', 'expired')),
  constraint agent_actions_source check (source in ('agent', 'loop', 'owner'))
);

create index if not exists agent_actions_restaurant_status on agent_actions (restaurant_id, status);
create index if not exists agent_actions_case on agent_actions (case_id);
create index if not exists agent_actions_created on agent_actions (restaurant_id, created_at desc);

-- Server only, like every table after 17_lockdown.sql
do $$
begin
  alter table agent_actions enable row level security;
  if not exists (select 1 from pg_policies where tablename = 'agent_actions' and policyname = 'server only') then
    create policy "server only" on agent_actions for all to service_role using (true) with check (true);
  end if;
end $$;
revoke all on agent_actions from anon, authenticated;
grant all on agent_actions to service_role;
