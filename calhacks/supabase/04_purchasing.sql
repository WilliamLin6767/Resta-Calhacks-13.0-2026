-- What the invoice says, not just what we calculate.
-- invoice_lines.line_total is calculated (qty * unit_price), so a supplier's math
-- error would be invisible. printed_total keeps the number actually printed.
alter table invoices
  add column if not exists subtotal           numeric(10,2),
  add column if not exists tax                numeric(10,2) default 0,
  add column if not exists purchase_order_id  bigint references purchase_orders(id) on delete set null,
  add column if not exists notes              text;

alter table invoice_lines
  add column if not exists item_code     text,          -- supplier's product code, if printed
  add column if not exists pack_desc     text,          -- pack size as printed, e.g. '6/25OZ'
  add column if not exists sold_by       text,          -- what the line is sold by: CS, LB, EA ...
  add column if not exists qty_ordered   numeric(10,2), -- if the invoice shows ordered vs shipped (qty = shipped)
  add column if not exists printed_total numeric(10,2), -- the line total as printed
  add column if not exists match_score   numeric(4,3),  -- 0-1: how sure the ingredient match is
  add column if not exists match_source  text,          -- learned, fuzzy, ai, ai_new, manual, seed
  add column if not exists needs_review  boolean not null default false;

-- Learned matches: this supplier's text means this ingredient.
-- Every time a person confirms a match it's saved here, so the next invoice is instant.
create table if not exists ingredient_aliases (
  id            bigint generated by default as identity primary key,
  restaurant_id bigint not null references restaurants(id) on delete cascade,
  supplier_id   bigint references suppliers(id) on delete cascade,  -- null = any supplier
  alias         text not null,                                       -- normalized invoice text
  ingredient_id bigint not null references ingredients(id) on delete cascade,
  source        text not null default 'confirmed' check (source in ('confirmed','auto','seed')),
  created_at    timestamptz not null default now(),
  unique nulls not distinct (restaurant_id, supplier_id, alias)
);

-- Problems found on an invoice, with the dollars at stake.
create table if not exists invoice_flags (
  id              bigint generated by default as identity primary key,
  invoice_id      bigint not null references invoices(id) on delete cascade,
  invoice_line_id bigint references invoice_lines(id) on delete cascade,
  ingredient_id   bigint references ingredients(id) on delete set null,
  kind            text not null check (kind in ('price_up','price_down','math','total_mismatch','short',
                    'overcharge','duplicate','cheaper_elsewhere','unmatched','unit')),
  severity        text not null check (severity in ('high','medium','info')),
  message         text not null,
  money_impact    numeric(10,2),     -- dollars at stake on this invoice
  -- for cheaper_elsewhere: who to buy from instead
  alt_supplier_id bigint references suppliers(id) on delete set null,
  alt_unit_price  numeric(10,2),
  resolved        boolean not null default false,
  created_at      timestamptz not null default now()
);
create index if not exists invoice_flags_invoice on invoice_flags (invoice_id);

-- (Lines the sample data already matched also count as learned matches: the app reads them directly.)
update invoice_lines set match_source = 'seed', match_score = 1 where ingredient_id is not null and match_source is null;
update invoice_lines set needs_review = true where ingredient_id is null;

