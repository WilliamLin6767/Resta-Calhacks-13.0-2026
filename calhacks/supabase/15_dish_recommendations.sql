-- =====================================================================
-- Dish recommendations from a Yelp and social scan. Run AFTER 01_schema.sql.
-- Safe to re-run.
--
-- Adds one table. Does not write menu_items or recipe_items, so the
-- current menu stays unchanged until the owner edits it.
-- =====================================================================

create table if not exists dish_recommendations (
  id                    bigint generated by default as identity primary key,
  restaurant_id         bigint not null references restaurants(id) on delete cascade,
  dish_name             text not null,
  demand_score          numeric not null,
  fit_score             numeric not null,
  recommend_score       numeric not null,
  new_ingredient_count  integer not null,
  have_ingredients      text[] not null default '{}',
  new_ingredients       text[] not null default '{}',
  reason                text not null,
  evidence              jsonb not null default '{}',
  scraped_at            timestamptz not null default now()
);

create index if not exists dish_recommendations_restaurant
  on dish_recommendations (restaurant_id, recommend_score desc);

-- DEMO ONLY: anyone with the publishable key can read and write. Same as the other tables.
do $$
begin
  alter table dish_recommendations enable row level security;
  if not exists (select 1 from pg_policies where tablename = 'dish_recommendations' and policyname = 'demo full access') then
    create policy "demo full access" on dish_recommendations for all to anon, authenticated using (true) with check (true);
  end if;
end $$;
